def draw_bitmap(img: Image.Image, rows: list[str], x: int, y: int, color, outline=None) -> None:
    px = img.load()
    pts = {(c, r) for r, row in enumerate(rows) for c, ch in enumerate(row) if ch == "#"}
    if outline is not None:
        for (c, r) in pts:
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + c + dx, y + r + dy
                if (c + dx, r + dy) not in pts and 0 <= nx < img.width and 0 <= ny < img.height:
                    px[nx, ny] = (*outline, 255)
    for (c, r) in pts:
        if 0 <= x + c < img.width and 0 <= y + r < img.height:
            px[x + c, y + r] = (*color, 255)
